async function resilienceTest() {

    let hostPort;
    let reqRate;

    const statusInterval = setInterval(() => {

        ({hostPort, reqRate } = requestStats());

    }, 3000);

    const kingdomKey = 6; // Plantae
    const year = '1800,1899';
    const limit = 300;
    let endOfRecords = false;

    for (let offset = 0; !endOfRecords; offset += limit) {

        const request = await fetchData('occurrenceYear', { kingdomKey, year, limit, offset });

        for (const result of request.results) {

            const request2 = await fetchData('speciesKey', { taxonKey: result.taxonKey });

            const taxonID = request2.taxonID;
            const name = request2.scientificName;

            logger.status(`«--» ${hostPort} | Req/sec: \x1b[33m${reqRate}\x1b[0m | ` +  
            `${taxonID} ${name} «--»`);
        }

        endOfRecords = request.endOfRecords;
    }

    clearInterval(statusInterval);
}

async function asyncBurstTest() {

    let hostPort;
    let reqRate;

    const statusInterval = setInterval(() => {

        ({hostPort, reqRate } = requestStats());

    }, 3000);

    const kingdomKey = 6; // Plantae
    const year = '1800,1899';
    const limit = 300;
    let endOfRecords = false;

    for (let offset = 0; !endOfRecords; offset += limit) {

        const request = await fetchData('occurrenceYear', { kingdomKey, year, limit, offset });

        const requestSize = request.results.length;

        for (let idx = 0; idx < requestSize; idx += 5) {

            const singleTask = async (index) => {

                if (index >= requestSize) return;

                const taxonKey = request.results[index].taxonKey;

                const request2 = await fetchData('speciesKey', { taxonKey });

                const taxonID = request2.taxonID;

                const name = request2.scientificName;

                logger.log(taxonID, name);

                logger.status(`«--» ${hostPort} | Req/sec: \x1b[33m${reqRate}\x1b[0m | ` +  
                `${taxonID} ${name} «--»`);
            }

            await Promise.all([
                singleTask(idx),
                singleTask(idx + 1),
                singleTask(idx + 2),
                singleTask(idx + 3),
                singleTask(idx + 4),
            ]);
        }

        endOfRecords = request.endOfRecords;
    }

    clearInterval(statusInterval);
}

